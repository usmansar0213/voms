import { getRouteApi, Link } from '@tanstack/react-router'
import { ArrowLeft, Printer } from 'lucide-react'
import { Button } from '@/components/ui/button'
import { Table, TableBody, TableCell, TableHead, TableHeader, TableRow } from '@/components/ui/table'
import { PageShell } from '@/components/layout/page-shell'
import { closureChecklist, delayHours, eventLabels, eventOrder, lineProgress, productivity, sequenceIssues, turnaround } from '../calc'
import { fmtDateTime, fmtHours, fmtNum, fmtQty, sourceLabel } from '../format'
import { can, roleById } from '../roles'
import { useVoms, visibleCalls } from '../store'
import { EmptyState, KeyValues, StatusBadge } from '../components/common'
import { scenarioLabel } from './vessel-calls'

const route = getRouteApi('/_app/reports/$callId')

function Section({ n, title, children }: { n: number; title: string; children: React.ReactNode }) {
  return (
    <section className='grid gap-3 break-inside-avoid'>
      <h2 className='border-b pb-1 text-base font-semibold'>
        {n}. {title}
      </h2>
      {children}
    </section>
  )
}

export function CallReport() {
  const { callId } = route.useParams()
  const state = useVoms()
  const call = visibleCalls(state).find((c) => c.id === callId)
  if (!call)
    return (
      <PageShell>
        <EmptyState>Report not available for {callId}.</EmptyState>
      </PageShell>
    )
  const vessel = state.vessels.find((v) => v.id === call.vesselId)!
  const berth = state.berths.find((b) => b.id === call.berthId)
  const incidents = state.incidents.filter((i) => i.callId === call.id)
  const t = turnaround(call)
  const checklist = closureChecklist(call, state.incidents)
  const issues = sequenceIssues(call)

  return (
    <PageShell className='max-w-4xl'>
      <div className='no-print flex flex-wrap justify-between gap-2'>
        <Button variant='ghost' size='sm' asChild>
          <Link to='/vessel-calls/$callId' params={{ callId: call.id }}>
            <ArrowLeft /> Back to vessel call
          </Link>
        </Button>
        {can(state, 'report.export') && (
          <Button size='sm' onClick={() => window.print()}>
            <Printer /> Print / save as PDF
          </Button>
        )}
      </div>

      <article className='grid gap-6 rounded-xl border bg-card p-4 text-sm sm:p-8 print:border-0 print:p-0'>
        <header className='grid gap-2'>
          <div className='text-xs tracking-wide text-muted-foreground uppercase'>PORTIX · Port of Subic Bay (demo)</div>
          <h1 className='text-xl font-bold'>Integrated Vessel Call Report</h1>
          <div className='flex flex-wrap items-center gap-2'>
            <span className='font-semibold'>{call.id}</span>
            <StatusBadge call={call} />
          </div>
          <p className='rounded-md border border-dashed p-2 text-xs text-muted-foreground'>
            SIMULATED DATA — generated by the PORTIX demonstration. Not an official SBMA record. Generated {fmtDateTime(new Date().toISOString())}.
          </p>
        </header>

        <Section n={1} title='Vessel and call information'>
          <KeyValues
            items={[
              ['Vessel', vessel.name],
              ['IMO number', vessel.imo],
              ['Vessel type', `${vessel.typeLabel} (${scenarioLabel[call.scenario]} scenario)`],
              ['Dimensions', `LOA ${vessel.loa} m · draft ${vessel.draft} m · DWT ${fmtNum(vessel.dwt)}`],
              ['Voyage (in / out)', `${call.voyageIn} / ${call.voyageOut}`],
              ['Last / next port', `${call.lastPort} / ${call.nextPort}`],
              ['Port call purpose', call.purpose],
              ['Berth', berth ? `${berth.id} (placeholder)` : 'Not assigned'],
            ]}
          />
        </Section>

        <Section n={2} title='Movement events'>
          <div className='overflow-x-auto'>
            <Table>
              <TableHeader>
                <TableRow>
                  <TableHead>Event</TableHead>
                  <TableHead>Time</TableHead>
                  <TableHead>Source</TableHead>
                  <TableHead>Recorded / verified</TableHead>
                </TableRow>
              </TableHeader>
              <TableBody>
                {(['eta', ...eventOrder, 'etd'] as const).map((k) => {
                  const e = call.events[k]
                  return (
                    <TableRow key={k}>
                      <TableCell>{eventLabels[k]}</TableCell>
                      <TableCell className='tabular-nums'>{fmtDateTime(e?.time)}</TableCell>
                      <TableCell>{e ? sourceLabel[e.source] : '—'}</TableCell>
                      <TableCell className='text-xs'>{e ? `${roleById[e.recordedBy].short}${e.verifiedBy ? ` / ${roleById[e.verifiedBy].short}` : k === 'eta' || k === 'etd' ? '' : ' / pending'}` : '—'}</TableCell>
                    </TableRow>
                  )
                })}
              </TableBody>
            </Table>
          </div>
          {issues.length > 0 && <p className='text-xs'>Sequence warnings: {issues.join('; ')}</p>}
        </Section>

        <Section n={3} title='Time performance'>
          <KeyValues
            items={[
              ['Waiting + berthing (ATA → All Fast)', fmtHours(t.waiting)],
              ['Time at berth (All Fast → Last Line)', fmtHours(t.atBerth)],
              ['Unberthing to departure (Last Line → ATD)', fmtHours(t.departure)],
              ['Total turnaround (ATA → ATD)', fmtHours(t.total)],
              ['Recorded delays', fmtHours(delayHours(call))],
            ]}
          />
        </Section>

        <Section n={4} title='Cargo and terminal operations'>
          <div className='overflow-x-auto'>
            <Table>
              <TableHeader>
                <TableRow>
                  <TableHead>Commodity</TableHead>
                  <TableHead>Direction</TableHead>
                  <TableHead className='text-end'>Declared</TableHead>
                  <TableHead className='text-end'>Actual</TableHead>
                  <TableHead className='text-end'>Verified</TableHead>
                  <TableHead className='text-end'>Variance</TableHead>
                </TableRow>
              </TableHeader>
              <TableBody>
                {call.cargo.map((l) => {
                  const p = lineProgress(call, l.id)
                  return (
                    <TableRow key={l.id}>
                      <TableCell>
                        {l.commodity}
                        {l.dangerous && ' (DG)'}
                      </TableCell>
                      <TableCell className='capitalize'>{l.direction}</TableCell>
                      <TableCell className='text-end tabular-nums'>{fmtQty(l.declared, l.unit)}</TableCell>
                      <TableCell className='text-end tabular-nums'>{fmtQty(p.done, l.unit)}</TableCell>
                      <TableCell className='text-end tabular-nums'>{fmtQty(p.verified, l.unit)}</TableCell>
                      <TableCell className='text-end tabular-nums'>{fmtQty(p.variance, l.unit)}</TableCell>
                    </TableRow>
                  )
                })}
              </TableBody>
            </Table>
          </div>
          {productivity(call).map((p) => (
            <p key={p.unit} className='text-xs'>
              Productivity ({p.unit}): gross {fmtNum(p.gross, 1)} {p.unit}/h over {fmtHours(p.grossHours)}; net {fmtNum(p.net, 1)} {p.unit}/h over {fmtHours(p.netHours)}.
            </p>
          ))}
          {call.delays.length > 0 && (
            <ul className='list-disc ps-5 text-xs'>
              {call.delays.map((d) => (
                <li key={d.id}>
                  {d.category}: {fmtDateTime(d.start)} → {d.end ? fmtDateTime(d.end) : 'ongoing'} {d.remarks && `— ${d.remarks}`}
                </li>
              ))}
            </ul>
          )}
          <p className='text-xs'>
            Final tally:{' '}
            {call.finalTally
              ? `submitted ${fmtDateTime(call.finalTally.at)}; ${call.finalTally.verifiedBy ? `verified ${fmtDateTime(call.finalTally.verifiedAt)}` : 'verification pending'}`
              : 'not submitted'}
          </p>
        </Section>

        <Section n={5} title='Safety, security and environmental incidents'>
          {incidents.length === 0 ? (
            <p>No incidents linked to this vessel call.</p>
          ) : (
            <ul className='grid gap-1'>
              {incidents.map((i) => (
                <li key={i.id}>
                  <span className='font-medium'>{i.id}</span> · {i.severity} · {i.title} · status: {i.status.replace('_', ' ')}
                </li>
              ))}
            </ul>
          )}
        </Section>

        <Section n={6} title='Closure status'>
          <ul className='grid gap-1'>
            {checklist.map((c) => (
              <li key={c.label}>
                {c.ok ? '✔' : c.blocking ? '✖' : '!'} {c.label}
              </li>
            ))}
          </ul>
          <p>{call.closure ? `Closed ${fmtDateTime(call.closure.at)} by ${roleById[call.closure.by].name}.` : 'Vessel call not closed.'}</p>
        </Section>
      </article>
    </PageShell>
  )
}
